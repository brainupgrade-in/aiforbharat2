export function t(key, lang, replacements = {}) {
  const s = strings[key]
  if (!s) return key
  let text = s[lang] || s.en
  Object.entries(replacements).forEach(([k, v]) => {
    text = text.replace(`{${k}}`, v)
  })
  return text
}
